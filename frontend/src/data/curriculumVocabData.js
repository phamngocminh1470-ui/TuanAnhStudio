// Helper: Lọc từ vựng theo khối lớp
export function getVocabByGrade(grade) {
  if (!grade) return CURRICULUM_VOCABULARY;
  return CURRICULUM_VOCABULARY.filter(item => String(item.grade) === String(grade));
}

// Helper: Lấy danh sách tất cả các Unit trong một khối lớp
export function getAllUnitsForGrade(grade) {
  const words = getVocabByGrade(grade);
  const unitsMap = {};
  words.forEach(w => {
    if (!unitsMap[w.unit]) {
      unitsMap[w.unit] = { unit: w.unit, title: w.unitTitle, count: 0 };
    }
    unitsMap[w.unit].count += 1;
  });
  return Object.values(unitsMap);
}

// Helper: Lấy danh sách từ vựng của một Unit cụ thể trong một khối lớp
export function getVocabByUnit(grade, unit) {
  const gradeWords = getVocabByGrade(grade);
  if (!unit || unit === 'all') return gradeWords;
  return gradeWords.filter(w => w.unit === unit);
}

// Helper: Tìm kiếm từ vựng (hỗ trợ cả tiếng Anh lẫn tiếng Việt không dấu)
export function searchVocab(query, grade = null) {
  if (!query) return grade ? getVocabByGrade(grade) : CURRICULUM_VOCABULARY;
  const q = query.toLowerCase().trim();
  const pool = grade ? getVocabByGrade(grade) : CURRICULUM_VOCABULARY;
  return pool.filter(item => 
    item.word.toLowerCase().includes(q) ||
    item.meaning.toLowerCase().includes(q) ||
    (item.collocation && item.collocation.toLowerCase().includes(q)) ||
    (item.unitTitle && item.unitTitle.toLowerCase().includes(q))
  );
}
